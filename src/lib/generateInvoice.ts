import jsPDF from "jspdf";

interface InvoiceData {
  invoiceNumber: string;
  date: string;
  clientName: string;
  clientEmail?: string | null;
  clientCompany?: string | null;
  projectName?: string | null;
  amount: number;
  description?: string | null;
  status: string;
}

export function generateInvoicePDF(data: InvoiceData) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 20;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  // Colors
  const primary = [26, 115, 102]; // teal
  const dark = [30, 35, 50];
  const muted = [120, 130, 145];
  const light = [245, 247, 250];

  // Header bar
  doc.setFillColor(primary[0], primary[1], primary[2]);
  doc.rect(0, 0, pageWidth, 45, "F");

  // Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(24);
  doc.setTextColor(255, 255, 255);
  doc.text("INVOICE", margin, 30);

  // Invoice number
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(`#${data.invoiceNumber}`, pageWidth - margin, 22, { align: "right" });
  doc.text(`Date: ${data.date}`, pageWidth - margin, 30, { align: "right" });

  y = 65;

  // Status badge
  doc.setFontSize(9);
  const statusColor = data.status === "paid" ? [34, 139, 34] : data.status === "overdue" ? [200, 50, 50] : [200, 150, 30];
  doc.setFillColor(statusColor[0], statusColor[1], statusColor[2]);
  const statusText = data.status.toUpperCase();
  const statusWidth = doc.getTextWidth(statusText) + 10;
  doc.roundedRect(margin, y - 7, statusWidth, 12, 2, 2, "F");
  doc.setTextColor(255, 255, 255);
  doc.text(statusText, margin + 5, y);

  y += 20;

  // Bill To section
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.setTextColor(muted[0], muted[1], muted[2]);
  doc.text("BILL TO", margin, y);

  y += 8;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(dark[0], dark[1], dark[2]);
  doc.text(data.clientName, margin, y);

  y += 7;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(muted[0], muted[1], muted[2]);
  if (data.clientCompany) {
    doc.text(data.clientCompany, margin, y);
    y += 6;
  }
  if (data.clientEmail) {
    doc.text(data.clientEmail, margin, y);
    y += 6;
  }

  y += 15;

  // Table header
  doc.setFillColor(light[0], light[1], light[2]);
  doc.rect(margin, y - 5, contentWidth, 14, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(muted[0], muted[1], muted[2]);
  doc.text("DESCRIPTION", margin + 5, y + 3);
  doc.text("AMOUNT", pageWidth - margin - 5, y + 3, { align: "right" });

  y += 18;

  // Table row
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(dark[0], dark[1], dark[2]);

  const descLines: string[] = [];
  if (data.projectName) descLines.push(`Project: ${data.projectName}`);
  if (data.description) descLines.push(data.description);
  if (descLines.length === 0) descLines.push("Professional services");

  descLines.forEach((line, i) => {
    doc.text(line, margin + 5, y + i * 6);
  });

  doc.setFont("helvetica", "bold");
  doc.text(`$${data.amount.toFixed(2)}`, pageWidth - margin - 5, y, { align: "right" });

  y += Math.max(descLines.length * 6, 6) + 5;

  // Divider
  doc.setDrawColor(220, 225, 230);
  doc.setLineWidth(0.5);
  doc.line(margin, y, pageWidth - margin, y);

  y += 12;

  // Total
  doc.setFillColor(light[0], light[1], light[2]);
  doc.rect(pageWidth - margin - 80, y - 6, 80, 20, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(muted[0], muted[1], muted[2]);
  doc.text("TOTAL", pageWidth - margin - 75, y + 4);
  doc.setFontSize(14);
  doc.setTextColor(primary[0], primary[1], primary[2]);
  doc.text(`$${data.amount.toFixed(2)}`, pageWidth - margin - 5, y + 5, { align: "right" });

  // Footer
  const footerY = doc.internal.pageSize.getHeight() - 25;
  doc.setDrawColor(220, 225, 230);
  doc.line(margin, footerY - 5, pageWidth - margin, footerY - 5);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(muted[0], muted[1], muted[2]);
  doc.text("Generated by LifeHub", margin, footerY);
  doc.text("Thank you for your business!", pageWidth - margin, footerY, { align: "right" });

  // Save
  doc.save(`invoice-${data.invoiceNumber}.pdf`);
}
